fn push_chip(out: &mut String, label: &str, value: &str) {
    let _ = write!(
        out,
        "<span class=\"chip\"><b>{}</b><span>{}</span></span>",
        esc(label),
        esc(value)
    );
}

#[derive(Default)]
struct Stats {
    messages: usize,
    users: usize,
    assistants: usize,
    tools: usize,
    cost: f64,
    tokens_in: u64,
    tokens_out: u64,
    reasoning: u64,
    cache_read: u64,
    cache_write: u64,
}

impl Stats {
    fn collect(export: &Export) -> Self {
        let mut stats = Stats::default();
        let mut sum_cost = 0.0_f64;

        for message in &export.messages {
            stats.messages += 1;
            match message.kind.as_str() {
                "user" => stats.users += 1,
                "assistant" => stats.assistants += 1,
                _ => {}
            }
            if message.kind != "assistant" {
                continue;
            }
            stats.tools += message
                .content
                .iter()
                .filter(|part| part.get("type").and_then(Value::as_str) == Some("tool"))
                .count();
            sum_cost += message.cost.unwrap_or(0.0);
            if let Some(tokens) = &message.tokens {
                stats.tokens_in += tokens.input.unwrap_or(0);
                stats.tokens_out += tokens.output.unwrap_or(0);
                stats.reasoning += tokens.reasoning.unwrap_or(0);
                stats.cache_read += tokens
                    .cache
                    .as_ref()
                    .and_then(|c| c.read)
                    .unwrap_or(0);
                stats.cache_write += tokens
                    .cache
                    .as_ref()
                    .and_then(|c| c.write)
                    .unwrap_or(0);
            }
        }

        if let Some(tokens) = &export.info.tokens {
            stats.tokens_in = tokens.input.unwrap_or(0);
            stats.tokens_out = tokens.output.unwrap_or(0);
            stats.reasoning = tokens.reasoning.unwrap_or(0);
            stats.cache_read = tokens.cache.as_ref().and_then(|c| c.read).unwrap_or(0);
            stats.cache_write = tokens.cache.as_ref().and_then(|c| c.write).unwrap_or(0);
        }
        stats.cost = export.info.cost.unwrap_or(sum_cost);
        stats
    }

    fn render(&self) -> String {
        let mut out = String::new();
        out.push_str(&card(
            "messages",
            &fmt_int(self.messages as u64),
            &format!("{} user · {} assistant", self.users, self.assistants),
        ));
        out.push_str(&card("tool calls", &fmt_int(self.tools as u64), ""));
        out.push_str(&card("cost", &fmt_cost(self.cost), ""));
        out.push_str(&card(
            "tokens in",
            &fmt_int(self.tokens_in),
            &format!(
                "{} cache read · {} written",
                fmt_int(self.cache_read),
                fmt_int(self.cache_write)
            ),
        ));
        out.push_str(&card(
            "tokens out",
            &fmt_int(self.tokens_out),
            &format!("{} reasoning", fmt_int(self.reasoning)),
        ));
        out
    }
}

fn card(label: &str, value: &str, hint: &str) -> String {
    let mut out = format!(
        "<div class=\"stat\"><div class=\"label\">{}</div><div class=\"value\">{}</div>",
        esc(label),
        esc(value)
    );
    if !hint.is_empty() {
        let _ = write!(out, "<div class=\"hint\">{}</div>", esc(hint));
    }
    out.push_str("</div>");
    out
}

