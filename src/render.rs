fn render_md(source: &str) -> String {
    let mut options = Options::empty();
    options.insert(Options::ENABLE_TABLES);
    options.insert(Options::ENABLE_STRIKETHROUGH);
    options.insert(Options::ENABLE_TASKLISTS);

    let parser = Parser::new_ext(source, options)
        .filter(|event| !matches!(event, Event::Html(_) | Event::InlineHtml(_)));

    let mut out = String::new();
    html::push_html(&mut out, parser);
    out
}

fn code_block(text: &str) -> String {
    let (shown, cut) = truncate_keep(text, MAX_BLOCK_CHARS);
    let mut out = String::new();
    out.push_str("<div class=\"code-wrap\"><pre class=\"code\">");
    out.push_str(&esc(&shown));
    out.push_str("</pre><button class=\"copy\" type=\"button\">copy</button></div>");
    if cut {
        out.push_str("<div class=\"trunc\">Truncated for display.</div>");
    }
    out
}

fn shell_code_block(text: &str) -> String {
    let (shown, cut) = truncate_keep(text, MAX_BLOCK_CHARS);
    let mut out = String::new();
    out.push_str("<div class=\"code-wrap\"><pre class=\"code shell\">");
    out.push_str(&highlight_shell(&shown));
    out.push_str("</pre><button class=\"copy\" type=\"button\">copy</button></div>");
    if cut {
        out.push_str("<div class=\"trunc\">Truncated for display.</div>");
    }
    out
}

fn highlight_shell(source: &str) -> String {
    let chars: Vec<char> = source.chars().collect();
    let mut out = String::with_capacity(source.len() + source.len() / 3);
    let mut i = 0;
    let mut expect_command = true;

    while i < chars.len() {
        let c = chars[i];

        if c == '\n' {
            out.push('\n');
            expect_command = true;
            i += 1;
            continue;
        }

        if c.is_whitespace() {
            out.push(c);
            i += 1;
            continue;
        }

        if c == '#' && (i == 0 || chars[i - 1].is_whitespace() || is_shell_operator(chars[i - 1])) {
            let start = i;
            while i < chars.len() && chars[i] != '\n' {
                i += 1;
            }
            sh_span(&mut out, "sh-comment", &chars[start..i]);
            continue;
        }

        if c == '\'' || c == '"' {
            let quote = c;
            let start = i;
            i += 1;
            while i < chars.len() {
                if quote == '"' && chars[i] == '\\' && i + 1 < chars.len() {
                    i += 2;
                    continue;
                }
                if chars[i] == quote {
                    i += 1;
                    break;
                }
                i += 1;
            }
            sh_span(&mut out, "sh-string", &chars[start..i]);
            expect_command = false;
            continue;
        }

        if c == '$' {
            let start = i;
            i += 1;
            if i < chars.len() && chars[i] == '{' {
                i += 1;
                while i < chars.len() && chars[i] != '}' {
                    i += 1;
                }
                if i < chars.len() {
                    i += 1;
                }
            } else if i < chars.len() && (chars[i].is_ascii_alphanumeric() || chars[i] == '_') {
                while i < chars.len() && (chars[i].is_ascii_alphanumeric() || chars[i] == '_') {
                    i += 1;
                }
            } else if i < chars.len() && chars[i] == '(' {
                sh_span(&mut out, "sh-var", &chars[start..start + 2]);
                i = start + 2;
                expect_command = true;
                continue;
            } else if i < chars.len() {
                i += 1;
            }
            sh_span(&mut out, "sh-var", &chars[start..i]);
            expect_command = false;
            continue;
        }

        if is_shell_operator(c) {
            let start = i;
            i += 1;
            while i < chars.len() && is_shell_operator(chars[i]) {
                i += 1;
            }
            sh_span(&mut out, "sh-op", &chars[start..i]);
            expect_command = matches!(chars[start], '|' | ';' | '&' | '(' | '{');
            continue;
        }

        let start = i;
        while i < chars.len()
            && !chars[i].is_whitespace()
            && !is_shell_operator(chars[i])
            && !matches!(chars[i], '\'' | '"' | '$')
        {
            i += 1;
        }

        let token: String = chars[start..i].iter().collect();
        let class = if is_shell_assignment(&token) {
            "sh-var"
        } else if expect_command {
            expect_command = is_command_wrapper(&token);
            "sh-cmd"
        } else if token.starts_with('-') {
            "sh-flag"
        } else {
            ""
        };

        if class.is_empty() {
            out.push_str(&esc(&token));
        } else {
            sh_span(&mut out, class, &chars[start..i]);
        }
    }

    out
}

fn sh_span(out: &mut String, class: &str, chars: &[char]) {
    let text: String = chars.iter().collect();
    let _ = write!(out, "<span class=\"{class}\">{}</span>", esc(&text));
}

fn is_shell_operator(c: char) -> bool {
    matches!(c, '|' | '&' | ';' | '<' | '>' | '(' | ')' | '{' | '}')
}

fn is_shell_assignment(token: &str) -> bool {
    let Some(eq) = token.find('=') else {
        return false;
    };
    let name = &token[..eq];
    let Some(first) = name.chars().next() else {
        return false;
    };
    !first.is_ascii_digit() && name.chars().all(|c| c.is_ascii_alphanumeric() || c == '_')
}

fn is_command_wrapper(token: &str) -> bool {
    matches!(
        token,
        "sudo" | "doas" | "env" | "time" | "command" | "exec" | "nice" | "nohup" | "xargs"
            | "watch"
    )
}

