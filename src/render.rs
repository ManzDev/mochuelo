/// Total time OpenCode was generating responses, excluding idle gaps between turns.
fn session_time(export: &Export) -> Option<i64> {
    let mut intervals: Vec<(i64, i64)> = export
        .messages
        .iter()
        .filter(|message| message.kind == "assistant")
        .filter_map(|message| {
            let time = message.time.as_ref()?;
            let start = time.created?;
            let end = time.completed?;
            (end >= start).then_some((start, end))
        })
        .collect();

    if intervals.is_empty() {
        return export.info.time.as_ref().and_then(InfoTime::wall);
    }

    intervals.sort_unstable();
    let (mut start, mut end) = intervals[0];
    let mut total = 0;
    for (next_start, next_end) in intervals.into_iter().skip(1) {
        if next_start <= end {
            end = end.max(next_end);
        } else {
            total += end - start;
            start = next_start;
            end = next_end;
        }
    }
    total += end - start;
    Some(total)
}

fn push_chip(out: &mut String, label: &str, value: &str) {
    let _ = write!(
        out,
        "<span class=\"chip\"><b>{}</b><span>{}</span></span>",
        esc(label),
        esc(value)
    );
}

#[derive(Default)]
struct Stats {
    messages: usize,
    users: usize,
    assistants: usize,
    tools: usize,
    cost: f64,
    tokens_in: u64,
    tokens_out: u64,
    reasoning: u64,
    cache_read: u64,
    cache_write: u64,
    costs: crate::pricing::Costs,
    cost_complete: bool,
    tool_counts: HashMap<String, usize>,
    tool_costs: HashMap<String, f64>,
}

impl Stats {
    fn collect(export: &Export, pricing: &crate::pricing::Pricing) -> Self {
        let mut stats = Stats::default();
        let mut sum_cost = 0.0_f64;

        for message in &export.messages {
            stats.messages += 1;
            match message.kind.as_str() {
                "user" => stats.users += 1,
                "assistant" => stats.assistants += 1,
                _ => {}
            }
            if message.kind != "assistant" {
                continue;
            }
            let mut tool_names: Vec<&str> = Vec::new();
            for part in &message.content {
                if part.get("type").and_then(Value::as_str) != Some("tool") {
                    continue;
                }
                let name = part
                    .get("name")
                    .and_then(Value::as_str)
                    .filter(|name| !name.is_empty())
                    .unwrap_or("unknown");
                tool_names.push(name);
            }

            stats.tools += tool_names.len();
            if !tool_names.is_empty() {
                // Tool-level costs are not in the export: distribute the message
                // cost evenly across its tool calls as an approximation.
                let share = message.cost.unwrap_or(0.0) / tool_names.len() as f64;
                for name in tool_names {
                    *stats.tool_counts.entry(name.to_string()).or_insert(0) += 1;
                    *stats.tool_costs.entry(name.to_string()).or_insert(0.0) += share;
                }
            }
            sum_cost += message.cost.unwrap_or(0.0);
            if let Some(tokens) = &message.tokens {
                stats.tokens_in += tokens.input.unwrap_or(0);
                stats.tokens_out += tokens.output.unwrap_or(0);
                stats.reasoning += tokens.reasoning.unwrap_or(0);
                stats.cache_read += tokens
                    .cache
                    .as_ref()
                    .and_then(|c| c.read)
                    .unwrap_or(0);
                stats.cache_write += tokens
                    .cache
                    .as_ref()
                    .and_then(|c| c.write)
                    .unwrap_or(0);
            }
        }

        if let Some(tokens) = &export.info.tokens {
            stats.tokens_in = tokens.input.unwrap_or(0);
            stats.tokens_out = tokens.output.unwrap_or(0);
            stats.reasoning = tokens.reasoning.unwrap_or(0);
            stats.cache_read = tokens.cache.as_ref().and_then(|c| c.read).unwrap_or(0);
            stats.cache_write = tokens.cache.as_ref().and_then(|c| c.write).unwrap_or(0);
        }
        let (costs, complete) = crate::pricing::breakdown(export, pricing);
        let recorded_cost = export.info.cost.unwrap_or(0.0);
        stats.cost = if sum_cost > 0.0 {
            sum_cost
        } else if recorded_cost > 0.0 {
            recorded_cost
        } else if complete {
            // OpenCode can leave info.cost and per-message costs at zero even
            // when tokens were billed. Fall back to the catalog estimate.
            costs.total()
        } else {
            0.0
        };
        stats.costs = costs;
        stats.cost_complete = complete;
        stats
    }

    fn render(&self) -> String {
        let mut out = String::new();

        let user_label = plural(self.users, "user prompt", "user prompts");
        let assistant_label = plural(self.assistants, "assistant message", "assistant messages");
        let message_bar = meter(
            &[
                ("user", self.users as u64),
                ("assistant", self.assistants as u64),
            ],
            &format!("{user_label} · {assistant_label}"),
        );
        out.push_str(&card_with_bar(
            "messages",
            &fmt_int(self.messages as u64),
            &format!("{user_label}\n{assistant_label}"),
            &message_bar,
        ));
        out.push_str(&tool_card(
            self.tools,
            &self.tool_counts,
            &self.tool_costs,
        ));
        out.push_str(&cost_card(self.cost, &self.costs, self.cost_complete));
        let total_input = self.tokens_in + self.cache_read + self.cache_write;
        let uncached_input = total_input.saturating_sub(self.cache_read);
        let cached_pct = if total_input == 0 {
            0.0
        } else {
            self.cache_read as f64 * 100.0 / total_input as f64
        };
        let input_hint = format!(
            "{} cached ({cached_pct:.1}%)\n{} uncached",
            fmt_compact(self.cache_read),
            fmt_compact(uncached_input)
        );
        let input_bar = meter(
            &[
                ("cached", self.cache_read),
                ("uncached", uncached_input),
            ],
            &format!(
                "{} cached ({cached_pct:.1}%), {} uncached tokens",
                fmt_compact(self.cache_read),
                fmt_compact(uncached_input)
            ),
        );

        let input_card = card_with_bar(
            "total/uncached input",
            &format!(
                "{} / {}",
                fmt_compact(total_input),
                fmt_compact(uncached_input)
            ),
            &input_hint,
            &input_bar,
        );

        let total_output = self.tokens_out + self.reasoning;
        let output_hint = {
            let mut hint = format!("{} output", fmt_compact(self.tokens_out));
            if self.reasoning > 0 {
                hint.push_str(&format!("\n{} reasoning", fmt_compact(self.reasoning)));
            }
            hint
        };
        let output_bar = meter(
            &[("output-uncached", total_output)],
            &format!("{} output tokens", fmt_compact(total_output)),
        );
        let output_card = card_with_bar(
            "total output",
            &fmt_compact(total_output),
            &output_hint,
            &output_bar,
        );

        let _ = write!(
            out,
            "<fieldset class=\"stats-group\"><legend>tokens</legend><div class=\"group-cards\">{input_card}{output_card}</div></fieldset>"
        );
        out
    }
}

fn meter(segments: &[(&str, u64)], aria: &str) -> String {
    let total: u64 = segments.iter().map(|(_, value)| *value).sum();
    let aria = esc(aria);
    let mut out = format!(
        "<div class=\"meter\" role=\"img\" aria-label=\"{aria}\" title=\"{aria}\">"
    );
    if total > 0 {
        for (class, value) in segments {
            if *value == 0 {
                continue;
            }
            let pct = *value as f64 * 100.0 / total as f64;
            let _ = write!(
                out,
                "<span class=\"meter-seg {class}\" style=\"width:{pct:.2}%\"></span>"
            );
        }
    }
    out.push_str("</div>");
    out
}

fn plural(count: usize, singular: &str, plural: &str) -> String {
    format!("{count} {}", if count == 1 { singular } else { plural })
}

fn tool_card(
    total: usize,
    counts: &HashMap<String, usize>,
    costs: &HashMap<String, f64>,
) -> String {
    let mut items: Vec<(&String, &usize)> = counts.iter().collect();
    items.sort_by(|a, b| b.1.cmp(a.1).then_with(|| a.0.cmp(b.0)));

    let mut out = format!(
        "<div class=\"stat stat-tools\"><div class=\"label\">tool calls</div><div class=\"value\">{}</div>",
        fmt_int(total as u64)
    );

    if !items.is_empty() {
        out.push_str("<div class=\"tool-list\">");
        for (name, count) in items {
            let icon = crate::icons::icon_id(name.as_str());
            let cost = costs.get(name.as_str()).copied().unwrap_or(0.0);
            let _ = write!(
                out,
                "<div class=\"tool-row\"><span class=\"tool-item\"><svg class=\"tool-icon\" aria-hidden=\"true\"><use href=\"#icon-{icon}\"></use></svg><span class=\"tool-item-name\" title=\"{}\">{}</span></span><span class=\"tool-metrics\"><span class=\"tool-count\">({})</span><span class=\"tool-cost\">{}</span></span></div>",
                esc(name),
                esc(name),
                fmt_int(*count as u64),
                fmt_cost(cost)
            );
        }
        out.push_str("</div>");
    }

    out.push_str("</div>");
    out
}

fn cost_card(total: f64, costs: &crate::pricing::Costs, complete: bool) -> String {
    let mut out = format!(
        "<div class=\"stat stat-cost\"><div class=\"label\">cost</div><div class=\"value\">{}</div>",
        esc(&fmt_cost(total))
    );

    if complete {
        let input = costs.input_cached + costs.input_uncached;
        out.push_str("<div class=\"cost-list\">");
        cost_row(&mut out, "Input", &fmt_cost(input), false);
        cost_row(
            &mut out,
            &format!("Cached ({})", fmt_compact(costs.input_cached_tokens)),
            &fmt_cost(costs.input_cached),
            true,
        );
        cost_row(
            &mut out,
            &format!("Uncached ({})", fmt_compact(costs.input_uncached_tokens)),
            &fmt_cost(costs.input_uncached),
            true,
        );
        cost_row(&mut out, "Output", &fmt_cost(costs.output_uncached), false);
        cost_row(
            &mut out,
            &format!("Uncached ({})", fmt_compact(costs.output_uncached_tokens)),
            &fmt_cost(costs.output_uncached),
            true,
        );
        out.push_str("</div>");
    } else {
        out.push_str("<div class=\"hint\">detailed cost unavailable</div>");
    }

    out.push_str("</div>");
    out
}

fn cost_row(out: &mut String, label: &str, value: &str, sub: bool) {
    let _ = write!(
        out,
        "<div class=\"cost-row{}\"><span>{}</span><span>{}</span></div>",
        if sub { " sub" } else { "" },
        esc(label),
        esc(value)
    );
}

fn card_with_bar(label: &str, value: &str, hint: &str, bar: &str) -> String {
    let mut out = format!(
        "<div class=\"stat\"><div class=\"label\">{}</div><div class=\"value\">{}</div>",
        esc(label),
        esc(value)
    );
    if !bar.is_empty() {
        out.push_str(bar);
    }
    if !hint.is_empty() {
        let _ = write!(out, "<div class=\"hint\">{}</div>", esc(hint));
    }
    out.push_str("</div>");
    out
}

