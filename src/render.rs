fn render_md(source: &str) -> String {
    let mut options = Options::empty();
    options.insert(Options::ENABLE_TABLES);
    options.insert(Options::ENABLE_STRIKETHROUGH);
    options.insert(Options::ENABLE_TASKLISTS);

    let parser = Parser::new_ext(source, options)
        .filter(|event| !matches!(event, Event::Html(_) | Event::InlineHtml(_)));

    let mut out = String::new();
    html::push_html(&mut out, parser);
    out
}

fn code_block(text: &str) -> String {
    let (shown, cut) = truncate_keep(text, MAX_BLOCK_CHARS);
    let mut out = String::new();
    out.push_str("<div class=\"code-wrap\"><pre class=\"code\">");
    out.push_str(&esc(&shown));
    out.push_str("</pre><button class=\"copy\" type=\"button\">copy</button></div>");
    if cut {
        out.push_str("<div class=\"trunc\">Truncated for display.</div>");
    }
    out
}

