fn render_message(message: &Message, idx: usize) -> String {
    let mut out = String::new();
    let time = message
        .time
        .as_ref()
        .and_then(|t| t.created)
        .map(fmt_ts)
        .unwrap_or_default();

    match message.kind.as_str() {
        "user" => {
            out.push_str(&msg_open(message, idx, "user"));
            out.push_str(
                "<header class=\"msg-head\"><span class=\"avatar user\">Y</span><div class=\"who\"><strong>You</strong>",
            );
            push_ts(&mut out, &time);
            out.push_str("</div></header>");

            let text = message.text.as_deref().unwrap_or("").trim();
            if !text.is_empty() {
                let _ = write!(out, "<div class=\"md\">{}</div>", render_md(text));
            }
            if !message.agents.is_empty() {
                out.push_str("<div class=\"files\">");
                for agent in &message.agents {
                    let _ = write!(out, "<span class=\"file\">@{}</span>", esc(agent));
                }
                out.push_str("</div>");
            }
            out.push_str(&render_files(&message.files));
            out.push_str("</article>");
        }
        "assistant" => out.push_str(&render_assistant(message, idx, &time)),
        other => {
            out.push_str(&msg_open(message, idx, "other"));
            let _ = write!(
                out,
                "<header class=\"msg-head\"><span class=\"avatar other\">?</span><div class=\"who\"><strong>{}</strong>",
                esc(other)
            );
            push_ts(&mut out, &time);
            out.push_str("</div></header>");
            let _ = write!(
                out,
                "<p class=\"muted\">Message type <code>{}</code> is not rendered.</p>",
                esc(other)
            );
            out.push_str("</article>");
        }
    }

    out
}

fn msg_open(message: &Message, idx: usize, role: &str) -> String {
    let mut out = format!("<article class=\"msg {role}\" id=\"m{idx}\"");
    if let Some(id) = &message.id {
        if !id.is_empty() {
            let _ = write!(out, " data-msg-id=\"{}\"", esc(id));
        }
    }
    out.push('>');
    out
}

fn push_ts(out: &mut String, time: &str) {
    if !time.is_empty() {
        let _ = write!(out, "<span class=\"ts\">{}</span>", esc(time));
    }
}

fn render_assistant(message: &Message, idx: usize, time: &str) -> String {
    let mut out = String::new();

    let created = message.time.as_ref().and_then(|t| t.created);
    let completed = message.time.as_ref().and_then(|t| t.completed);
    let duration = match (created, completed) {
        (Some(start), Some(end)) if end >= start => Some(end - start),
        _ => None,
    };

    let agent = message.agent.as_deref().unwrap_or("assistant");
    let model = message.model.as_ref().and_then(|m| {
        Some(format!(
            "{}/{}",
            m.provider_id.as_deref().unwrap_or("?"),
            m.id.as_deref()?
        ))
    });

    out.push_str(&msg_open(message, idx, "assistant"));    out.push_str(
        "<header class=\"msg-head\"><span class=\"avatar assistant\">AI</span><div class=\"who\">",
    );
    let _ = write!(out, "<strong>{}</strong>", esc(agent));
    push_ts(&mut out, time);
    if let Some(model) = &model {
        let _ = write!(out, "<span class=\"model\">{}</span>", esc(model));
    }
    out.push_str("</div>");

    let mut meta: Vec<String> = Vec::new();
    if let Some(duration) = duration {
        meta.push(fmt_duration(duration));
    }
    if let Some(cost) = message.cost {
        if cost > 0.0 {
            meta.push(fmt_cost(cost));
        }
    }
    if let Some(tokens) = &message.tokens {
        let input = tokens.input.unwrap_or(0);
        let output = tokens.output.unwrap_or(0);
        if input > 0 || output > 0 {
            meta.push(format!(
                "<span class=\"up\" title=\"input tokens\">↑{}</span> <span class=\"down\" title=\"output tokens\">↓{}</span>",
                fmt_compact(input),
                fmt_compact(output)
            ));
        }
    }
    if let Some(finish) = &message.finish {
        if !matches!(finish.as_str(), "stop" | "tool_calls" | "tool-calls") {
            meta.push(esc(finish));
        }
    }
    if !meta.is_empty() {
        let _ = write!(out, "<div class=\"msg-meta\">{}</div>", meta.join(" · "));
    }
    out.push_str("</header>");

    if let Some(error) = &message.error {
        out.push_str(&render_error(error));
    }

    for part in &message.content {
        match part.get("type").and_then(Value::as_str).unwrap_or("") {
            "text" => {
                let text = part
                    .get("text")
                    .and_then(Value::as_str)
                    .unwrap_or("")
                    .trim();
                if !text.is_empty() {
                    let _ = write!(out, "<div class=\"md\">{}</div>", render_md(text));
                }
            }
            "reasoning" => out.push_str(&render_reasoning(part)),
            "tool" => out.push_str(&render_tool(part)),
            "file" => out.push_str(&render_file_part(part)),
            _ => {}
        }
    }

    out.push_str("</article>");
    out
}

fn render_reasoning(part: &Value) -> String {
    let text = part
        .get("text")
        .and_then(Value::as_str)
        .unwrap_or("")
        .trim();
    if text.is_empty() {
        return String::new();
    }

    let duration = part.get("time").and_then(|time| {
        let start = time.get("created")?.as_i64()?;
        let end = time.get("completed")?.as_i64()?;
        (end >= start).then_some(end - start)
    });

    let mut out = String::new();
    out.push_str(
        "<details class=\"block reasoning\"><summary><span class=\"chev\">›</span><span class=\"rlabel\">reasoning</span>",
    );
    if let Some(duration) = duration {
        let _ = write!(out, "<span class=\"rdur\">{}</span>", fmt_duration(duration));
    }
    out.push_str("</summary><div class=\"body md\">");
    out.push_str(&render_md(text));
    out.push_str("</div></details>");
    out
}

fn render_tool(part: &Value) -> String {
    let name = part.get("name").and_then(Value::as_str).unwrap_or("tool");
    let state = part.get("state");
    let status = state
        .and_then(|s| s.get("status"))
        .and_then(Value::as_str)
        .unwrap_or("unknown");
    let input = state.and_then(|s| s.get("input"));

    let mut preview = state
        .and_then(|s| s.get("title"))
        .and_then(Value::as_str)
        .unwrap_or("")
        .to_string();
    if preview.trim().is_empty() {
        preview = input.map(preview_of).unwrap_or_default();
    }

    let status_class = match status {
        "completed" => "ok",
        "running" => "run",
        "error" => "err",
        _ => "",
    };
    let icon = crate::icons::icon_id(name);

    let mut out = String::new();
    let _ = write!(
        out,
        "<details class=\"block tool\"><summary><span class=\"chev\">›</span><svg class=\"tool-icon\" aria-hidden=\"true\"><use href=\"#icon-{icon}\"></use></svg><span class=\"tool-name\">{}</span><span class=\"tool-preview\">{}</span><span class=\"badge {}\">{}</span></summary><div class=\"tool-body\">",
        esc(name),
        esc(&preview),
        status_class,
        esc(status)
    );

    if let Some(input) = input {
        if !input.is_null() {
            out.push_str(&render_input(input));
        }
    }

    if let Some(error) = state.and_then(|s| s.get("error")) {
        if !error.is_null() {
            let text = error
                .as_str()
                .map(str::to_string)
                .unwrap_or_else(|| serde_json::to_string_pretty(error).unwrap_or_default());
            let _ = write!(
                out,
                "<div class=\"io-label\">Error</div><div class=\"callout\">{}</div>",
                esc(&text)
            );
        }
    }

    if let Some(output) = tool_output(state) {
        let _ = write!(
            out,
            "<div class=\"io-label\">Output</div>{}",
            code_block(&output)
        );
    }

    let mut meta_chips: Vec<String> = Vec::new();
    if let Some(metadata) = state.and_then(|s| s.get("metadata")) {
        if let Some(exit) = metadata.get("exit").and_then(Value::as_i64) {
            meta_chips.push(format!("exit {exit}"));
        }
        if metadata.get("truncated").and_then(Value::as_bool) == Some(true) {
            meta_chips.push("truncated by tool".to_string());
        }
    }
    if !meta_chips.is_empty() {
        out.push_str("<div class=\"tool-meta\">");
        for chip in meta_chips {
            let _ = write!(out, "<span class=\"badge\">{}</span>", esc(&chip));
        }
        out.push_str("</div>");
    }

    out.push_str("</div></details>");
    out
}

fn render_input(input: &Value) -> String {
    let mut out = String::from("<div class=\"io\"><div class=\"io-label\">Input</div>");

    if let Value::Object(map) = input {
        for (key, value) in map {
            if value.is_null() {
                continue;
            }
            if let Some(text) = value.as_str() {
                if text.is_empty() {
                    continue;
                }
                let block = if key == "command" {
                    shell_code_block(text)
                } else {
                    code_block(text)
                };
                let _ = write!(
                    out,
                    "<div class=\"kv\"><span class=\"kv-key\">{}</span>{}</div>",
                    esc(key),
                    block
                );
                continue;
            }
            if value.is_boolean() || value.is_number() {
                let _ = write!(
                    out,
                    "<div class=\"kv\"><span class=\"kv-key\">{}</span><span class=\"kv-scalar\">{}</span></div>",
                    esc(key),
                    esc(&value.to_string())
                );
                continue;
            }
            let pretty = serde_json::to_string_pretty(value).unwrap_or_default();
            let _ = write!(
                out,
                "<div class=\"kv\"><span class=\"kv-key\">{}</span>{}</div>",
                esc(key),
                code_block(&pretty)
            );
        }
    } else {
        let pretty = serde_json::to_string_pretty(input).unwrap_or_default();
        out.push_str(&code_block(&pretty));
    }

    out.push_str("</div>");
    out
}

fn tool_output(state: Option<&Value>) -> Option<String> {
    let state = state?;

    if let Some(output) = state.get("output").and_then(Value::as_str) {
        if !output.is_empty() {
            return Some(output.to_string());
        }
    }

    let content = state.get("content")?.as_array()?;
    let mut out = String::new();
    for item in content {
        if let Some(text) = item.get("text").and_then(Value::as_str) {
            out.push_str(text);
        } else if let Some(text) = item.get("content").and_then(Value::as_str) {
            out.push_str(text);
        }
    }
    (!out.is_empty()).then_some(out)
}

fn preview_of(input: &Value) -> String {
    const KEYS: [&str; 9] = [
        "command",
        "filePath",
        "path",
        "pattern",
        "query",
        "url",
        "description",
        "prompt",
        "name",
    ];

    if let Value::Object(map) = input {
        for key in KEYS {
            if let Some(text) = map.get(key).and_then(Value::as_str) {
                let flat = one_line(text);
                if !flat.is_empty() {
                    return truncate(&flat, 160);
                }
            }
        }
        for value in map.values() {
            if let Some(text) = value.as_str() {
                let flat = one_line(text);
                if !flat.is_empty() {
                    return truncate(&flat, 160);
                }
            }
        }
    }
    String::new()
}

fn render_error(error: &Value) -> String {
    let text = match error {
        Value::String(text) => text.clone(),
        Value::Object(map) => map
            .get("message")
            .and_then(Value::as_str)
            .or_else(|| {
                map.get("data")
                    .and_then(|data| data.get("message"))
                    .and_then(Value::as_str)
            })
            .map(str::to_string)
            .unwrap_or_else(|| serde_json::to_string_pretty(error).unwrap_or_default()),
        other => other.to_string(),
    };
    format!("<div class=\"callout\">⚠ {}</div>", esc(&text))
}

fn render_files(files: &[Value]) -> String {
    if files.is_empty() {
        return String::new();
    }

    let mut out = String::from("<div class=\"files\">");
    for file in files {
        let Some((label, url)) = file_entry(file) else {
            continue;
        };
        match url {
            Some(url) => {
                let _ = write!(
                    out,
                    "<a class=\"file\" href=\"{}\" target=\"_blank\" rel=\"noreferrer\">{}</a>",
                    esc(&url),
                    esc(&label)
                );
            }
            None => {
                let _ = write!(out, "<span class=\"file\">{}</span>", esc(&label));
            }
        }
    }
    out.push_str("</div>");
    out
}

fn render_file_part(part: &Value) -> String {
    render_files(std::slice::from_ref(part))
}

fn file_entry(file: &Value) -> Option<(String, Option<String>)> {
    match file {
        Value::String(text) => Some((text.clone(), None)),
        Value::Object(map) => {
            let label = map
                .get("filename")
                .and_then(Value::as_str)
                .or_else(|| map.get("name").and_then(Value::as_str))
                .or_else(|| map.get("url").and_then(Value::as_str))
                .unwrap_or("attachment");
            let url = map
                .get("url")
                .and_then(Value::as_str)
                .filter(|url| safe_url(url))
                .map(str::to_string);
            Some((label.to_string(), url))
        }
        _ => None,
    }
}

fn safe_url(url: &str) -> bool {
    url.starts_with("http://")
        || url.starts_with("https://")
        || url.starts_with("file://")
        || url.starts_with("data:image/")
}

