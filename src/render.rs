const MAX_BLOCK_CHARS: usize = 120_000;

const STYLE: &str = include_str!("assets/style.css");
const SCRIPT: &str = include_str!("assets/app.js");

pub fn render(export: &Export) -> String {
    let info = &export.info;
    let title = info
        .title
        .as_deref()
        .map(str::trim)
        .filter(|t| !t.is_empty())
        .unwrap_or("Untitled session");

    let stats = Stats::collect(export);

    let mut chips = String::new();
    push_chip(&mut chips, "agent", info.agent.as_deref().unwrap_or("unknown"));
    if let Some(model) = &info.model {
        let mut label = format!(
            "{}/{}",
            model.provider_id.as_deref().unwrap_or("?"),
            model.id.as_deref().unwrap_or("?")
        );
        if let Some(variant) = &model.variant {
            if variant != "default" {
                label.push_str(&format!(" · {variant}"));
            }
        }
        push_chip(&mut chips, "model", &label);
    }
    if let Some(project) = &info.project_id {
        push_chip(&mut chips, "project", &truncate(project, 12));
    }
    if let Some(dir) = info.location.as_ref().and_then(|l| l.directory.as_deref()) {
        push_chip(&mut chips, "directory", dir);
    }
    if let Some(created) = info.time.as_ref().and_then(|t| t.created) {
        push_chip(&mut chips, "started", &fmt_ts(created));
    }
    if let Some(wall) = info.time.as_ref().and_then(InfoTime::wall) {
        push_chip(&mut chips, "wall time", &fmt_duration(wall));
    }

    let mut timeline = String::new();
    for (idx, message) in export.messages.iter().enumerate() {
        timeline.push_str(&render_message(message, idx));
    }
    if export.messages.is_empty() {
        timeline.push_str("<p class=\"empty\">No messages in this session.</p>");
    }

    let generated = Local::now().format("%Y-%m-%d %H:%M").to_string();
    let count_label = format!("{} messages", export.messages.len());
    let title_html = esc(title);
    let id_html = esc(&info.id);

    let html = format!(
        r##"<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="color-scheme" content="dark light">
<title>{title_html} · oc-observe</title>
<style>{style}</style>
</head>
<body id="top">
<main class="wrap">
  <header class="hero">
    <div class="brand"><span class="dot"></span>oc-observe</div>
    <h1>{title_html}</h1>
    <div class="idline">
      <span class="session-id">{id_html}</span>
      <button class="copy-id" type="button" data-copy="{id_html}">copy id</button>
    </div>
    <div class="chips">{chips}</div>
  </header>

  <section class="stats">{stats_html}</section>

  <div class="toolbar">
    <label class="search" for="filter">
      <span class="sicon" aria-hidden="true">⌕</span>
      <input id="filter" type="search" placeholder="Filter messages…" autocomplete="off" spellcheck="false">
      <kbd>/</kbd>
    </label>
    <span class="count" id="filter-count">{count_label}</span>
    <button class="btn" type="button" data-act="expand">expand all</button>
    <button class="btn" type="button" data-act="collapse">collapse all</button>
  </div>

  <section class="timeline">{timeline}</section>

  <footer class="footer">
    <span>Generated by <code>oc-observe</code> · {generated}</span>
    <span><code>opencode session export {id_html}</code></span>
  </footer>
</main>
<a class="top" href="#top" title="Back to top" aria-label="Back to top">↑</a>
<script>{script}</script>
</body>
</html>
"##,
        title_html = title_html,
        id_html = id_html,
        style = STYLE,
        script = SCRIPT,
        chips = chips,
        stats_html = stats.render(),
        count_label = count_label,
        timeline = timeline,
        generated = generated,
    );

    html
}

